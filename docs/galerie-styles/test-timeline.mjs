import fs from 'node:fs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {designScenes, duration, videoSegments, validCutout} from '../../remotion/src/timeline.ts';
const file=new URL('./tests/infographie-apercu.json',import.meta.url);
const r=JSON.parse(fs.readFileSync(file,'utf8'));
const before=designScenes(r);
assert.ok(before.length);
const original=structuredClone(r);
const anchor=before[0];
r.clips[0].words.slice(0,anchor.index).forEach(w=>w.cut=true);
const after=designScenes(r);
assert.ok(after[0].at<anchor.at,'le graphisme suit son mot après une coupe');
assert.ok(after[0].end<=duration(r),'rien ne dépasse la fin');
r.clips[0].words[anchor.index].cut=true;
assert.equal(designScenes(r).length,0,'une ancre supprimée enlève la scène');
original.styleScenes.push({...original.styleScenes[0],id:'doublon'});
assert.equal(designScenes(original).length,1,'pas de chevauchement automatique');
original.design.enabled=false;
assert.equal(designScenes(original).length,0);
const seg=videoSegments(original)[0];
original.cutouts={[seg.clip]:{file:'assets/x.webm',source:seg.source,proxy:original.sources[seg.source].proxy,start:seg.src_in,end:seg.src_out,width:720,height:1280}};
assert.ok(validCutout(original,seg));
original.cutouts[seg.clip].source='autre-prise';
assert.equal(validCutout(original,seg),null,'ne jamais afficher le détourage d’une autre prise');
console.log('6 vérifications temporelles réussies');
